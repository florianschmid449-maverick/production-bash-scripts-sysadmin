#!/usr/bin/env bash
# ==============================================================================
# Script Name : ssh_hardening_auditor.sh
# Description : Audits local SSH daemon configuration (/etc/ssh/sshd_config)
#               against CIS Benchmark, calculating a 0-100 Security Hardening Score,
#               offering an interactive menu and exportable remediation guide.
# Author      : Florian Schmid
# Contact     : FlorianSchmid449@gmail.com
# Version     : 2.0.0
# License     : MIT
# Requirements: bash (>= 4.4), coreutils, grep
# ==============================================================================
set -euo pipefail
IFS=$'\n\t'

# ANSI Color & Style Codes
CYAN='\033[0;36m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BOLD='\033[1m'
DIM='\033[2m'
NC='\033[0m'

CONFIG_PATH="/etc/ssh/sshd_config"
INTERACTIVE=false

usage() {
    cat <<EOF
Usage: $(basename "$0") [OPTIONS]

Audits SSH daemon security configuration settings against CIS hardening baselines.

Options:
  -c, --config <path>   Path to sshd_config (default: /etc/ssh/sshd_config)
  -m, --menu            Launch interactive menu mode
  -h, --help            Show this help message and exit

Example:
  sudo $(basename "$0") --menu
EOF
    exit 0
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        -c|--config)
            CONFIG_PATH="$2"; shift 2 ;;
        -m|--menu)
            INTERACTIVE=true; shift ;;
        -h|--help)
            usage ;;
        *)
            echo -e "${RED}[ERROR]${NC} Unknown option: $1" >&2
            exit 2 ;;
    esac
done

TOTAL_POINTS=0
MAX_POINTS=80

audit_rule() {
    local directive="$1"
    local secure_val="$2"
    local weight="$3"
    local description="$4"

    local active_val
    active_val=$(grep -riE "^[[:space:]]*${directive}[[:space:]]+" "$CONFIG_PATH" /etc/ssh/sshd_config.d/*.conf 2>/dev/null | tail -n 1 | awk '{print $2}' || true)

    if [[ -n "$active_val" && "${active_val,,}" == "${secure_val,,}" ]]; then
        TOTAL_POINTS=$((TOTAL_POINTS + weight))
        echo -e "  ${GREEN}✔ [PASS (+${weight}pts)]${NC} ${BOLD}${directive}${NC} = ${active_val}"
    elif [[ -z "$active_val" ]]; then
        echo -e "  ${YELLOW}⚠ [DEFAULT (0pts)]${NC}  ${directive} is unset (Recommended: ${secure_val}) - ${description}"
    else
        echo -e "  ${RED}✖ [FAIL (0pts)]${NC}     ${directive} = ${active_val} (Recommended: ${secure_val}) - ${description}"
    fi
}

run_full_audit() {
    TOTAL_POINTS=0
    echo -e "${CYAN}====================================================================${NC}"
    echo -e "${BOLD}${CYAN} SSH Server Hardening Compliance & Security Score - Florian Schmid${NC}"
    echo -e "${CYAN}====================================================================${NC}"
    echo -e "Target Configuration: ${CONFIG_PATH}\n"

    if [[ ! -f "$CONFIG_PATH" || ! -r "$CONFIG_PATH" ]]; then
        echo -e "${YELLOW}[NOTICE] '${CONFIG_PATH}' is unreadable. Elevated privileges recommended.${NC}\n"
    fi

    echo -e "${YELLOW}Evaluating CIS SSH Baseline Controls:${NC}"
    audit_rule "PermitRootLogin" "no" 15 "Disallows root SSH logins directly over network"
    audit_rule "PasswordAuthentication" "no" 15 "Enforces cryptographic key-based logins"
    audit_rule "PermitEmptyPasswords" "no" 10 "Blocks login with blank or null passwords"
    audit_rule "MaxAuthTries" "3" 10 "Mitigates automated brute-force attacks"
    audit_rule "X11Forwarding" "no" 10 "Prevents unauthorized GUI session piggybacking"
    audit_rule "ClientAliveInterval" "300" 10 "Terminates stale unattended sessions"
    audit_rule "ClientAliveCountMax" "2" 5 "Disallows endless unanswered probes"
    audit_rule "PubkeyAuthentication" "yes" 5 "Enables modern SSH key pairs"

    local score_pct=$(( (TOTAL_POINTS * 100) / MAX_POINTS ))
    echo -e "\n────────────────────────────────────────────────────────────────────"
    echo -ne "System SSH Hardening Index: "
    if [[ "$score_pct" -ge 85 ]]; then
        echo -e "${GREEN}${BOLD}${score_pct} / 100 [EXCELLENT HARDENING]${NC}"
    elif [[ "$score_pct" -ge 60 ]]; then
        echo -e "${YELLOW}${BOLD}${score_pct} / 100 [MODERATE - REMEDIATION ADVISED]${NC}"
    else
        echo -e "${RED}${BOLD}${score_pct} / 100 [HIGH RISK - HARDENING REQUIRED]${NC}"
    fi
    echo -e "────────────────────────────────────────────────────────────────────\n"
}

export_hardened_config() {
    local target="/tmp/sshd_config_hardened.conf"
    cat << 'EOF' > "$target"
# ==============================================================================
# Hardened SSH Daemon Drop-in Configuration
# Generated by: ssh_hardening_auditor.sh (Florian Schmid)
# Destination : /etc/ssh/sshd_config.d/99-hardened.conf
# ==============================================================================
PermitRootLogin no
PasswordAuthentication no
PermitEmptyPasswords no
MaxAuthTries 3
X11Forwarding no
ClientAliveInterval 300
ClientAliveCountMax 2
PubkeyAuthentication yes
Protocol 2
EOF
    echo -e "${GREEN}[SUCCESS] Generated hardened drop-in template: ${target}${NC}"
    echo -e "To apply, copy to: sudo cp ${target} /etc/ssh/sshd_config.d/99-hardened.conf && sudo systemctl reload sshd"
}

if [[ "$INTERACTIVE" == true ]]; then
    while true; do
        clear
        run_full_audit
        echo -e "Interactive Menu:"
        echo -e "  [1] Re-run audit"
        echo -e "  [2] Generate hardened configuration drop-in file (/tmp)"
        echo -e "  [3] Exit"
        echo ""
        read -rp "Select an option [1-3]: " opt
        case "$opt" in
            1) continue ;;
            2)
                export_hardened_config
                read -rp "Press Enter to continue..." _
                ;;
            3) exit 0 ;;
            *) sleep 0.5 ;;
        esac
    done
else
    run_full_audit
fi

exit 0
